#!/bin/bash
# Regenerate home/.git-plugin-bash.sh from the installed Oh My Zsh git plugin.
#
# The zsh plugin's aliases are plain shell and are copied verbatim; its zsh
# functions are replaced by hand-written bash ports (see the heredoc below).
# Aliases that use zsh-only syntax are skipped and ported by hand instead.
#
# Usage: tools/update-git-plugin-bash.sh [path/to/git.plugin.zsh]

set -euo pipefail

ROOT_DIR="$(cd "$(dirname "$0")/.." && pwd)"
SRC="${1:-${ZSH:-$HOME/.oh-my-zsh}/plugins/git/git.plugin.zsh}"
DEST="$ROOT_DIR/home/.git-plugin-bash.sh"

# Aliases with zsh-only syntax, ported in the heredoc below
SKIP='^alias (gtl|gke)='

[ -r "$SRC" ] || { echo "Cannot read $SRC" >&2; exit 1; }

{
cat <<'EOF'
# shellcheck shell=bash
#
# Bash port of the Oh My Zsh git plugin (MIT License, (c) Oh My Zsh contributors):
# https://github.com/ohmyzsh/ohmyzsh/tree/master/plugins/git
#
# GENERATED by tools/update-git-plugin-bash.sh -- do not edit by hand.

#
# Functions
#

# Current branch name, or the short SHA on a detached HEAD
function git_current_branch() {
  local ref
  ref=$(command git symbolic-ref --quiet HEAD 2>/dev/null)
  local ret=$?
  if [[ $ret != 0 ]]; then
    [[ $ret == 128 ]] && return # no git repo
    ref=$(command git rev-parse --short HEAD 2>/dev/null) || return
  fi
  echo "${ref#refs/heads/}"
}

function git_develop_branch() {
  command git rev-parse --git-dir &>/dev/null || return
  local branch
  for branch in dev devel develop development; do
    if command git show-ref -q --verify "refs/heads/$branch"; then
      echo "$branch"
      return 0
    fi
  done
  echo develop
  return 1
}

function git_main_branch() {
  command git rev-parse --git-dir &>/dev/null || return
  local remote ref
  for ref in refs/{heads,remotes/{origin,upstream}}/{main,trunk,mainline,default,stable,master}; do
    if command git show-ref -q --verify "$ref"; then
      echo "${ref##*/}"
      return 0
    fi
  done
  for remote in origin upstream; do
    ref=$(command git rev-parse --abbrev-ref "$remote/HEAD" 2>/dev/null)
    if [[ $ref == $remote/* ]]; then
      echo "${ref#"$remote/"}"; return 0
    fi
  done
  echo master
  return 1
}

function grename() {
  if [[ -z "$1" || -z "$2" ]]; then
    echo "Usage: ${FUNCNAME[0]} old_branch new_branch"
    return 1
  fi
  git branch -m "$1" "$2"
  if git push origin :"$1"; then
    git push --set-upstream origin "$2"
  fi
}

function gunwipall() {
  local _commit
  _commit=$(git log --grep='--wip--' --invert-grep --max-count=1 --format=format:%H)
  if [[ "$_commit" != "$(git rev-parse HEAD)" ]]; then
    git reset "$_commit" || return 1
  fi
}

function work_in_progress() {
  command git -c log.showSignature=false log -n 1 2>/dev/null | grep -q -- "--wip--" && echo "WIP!!"
}

function ggpnp() {
  if [[ $# == 0 ]]; then
    ggl && ggp
  else
    ggl "${*}" && ggp "${*}"
  fi
}

function gbda() {
  git branch --no-color --merged | command grep -vE "^([+*]|\s*($(git_main_branch)|$(git_develop_branch))\s*$)" | command xargs git branch --delete 2>/dev/null
}

function gbds() {
  local default_branch branch merge_base
  default_branch=$(git_main_branch) || default_branch=$(git_develop_branch)
  git for-each-ref refs/heads/ "--format=%(refname:short)" |
    while read -r branch; do
      merge_base=$(git merge-base "$default_branch" "$branch")
      if [[ $(git cherry "$default_branch" "$(git commit-tree "$(git rev-parse "$branch^{tree}")" -p "$merge_base" -m _)") = -* ]]; then
        git branch -D "$branch"
      fi
    done
}

function gccd() {
  local repo="${!#}"
  command git clone --recurse-submodules "$@" || return
  repo="${repo%/}"; repo="${repo%.git}"
  cd "${repo##*/}" || return
}

function gdv() { git diff -w "$@" | view -; }

function gdnolock() {
  git diff "$@" ":(exclude)package-lock.json" ":(exclude)*.lock"
}

function _git_log_prettily() {
  if [ -n "$1" ]; then
    git log --pretty="$1"
  fi
}

function ggu() {
  local b
  [[ $# != 1 ]] && b="$(git_current_branch)"
  git pull --rebase origin "${b:-$1}"
}

function ggl() {
  if [[ $# != 0 ]] && [[ $# != 1 ]]; then
    git pull origin "${*}"
  else
    local b
    [[ $# == 0 ]] && b="$(git_current_branch)"
    git pull origin "${b:-$1}"
  fi
}

function ggf() {
  local b
  [[ $# != 1 ]] && b="$(git_current_branch)"
  git push --force origin "${b:-$1}"
}

function ggfl() {
  local b
  [[ $# != 1 ]] && b="$(git_current_branch)"
  git push --force-with-lease origin "${b:-$1}"
}

function ggp() {
  if [[ $# != 0 ]] && [[ $# != 1 ]]; then
    git push origin "${*}"
  else
    local b
    [[ $# == 0 ]] && b="$(git_current_branch)"
    git push origin "${b:-$1}"
  fi
}

function gtl() { git tag --sort=-v:refname -n --list "${1}*"; }

#
# Aliases (assumes git >= 2.30)
#

alias gfa='git fetch --all --tags --prune --jobs=10'
alias gpf='git push --force-with-lease --force-if-includes'
alias gpsupf='git push --set-upstream origin $(git_current_branch) --force-with-lease --force-if-includes'
alias gsta='git stash push'
alias gke='\gitk --all $(git log --walk-reflogs --pretty=%h) & disown'

EOF
grep -E '^alias ' "$SRC" | grep -vE "$SKIP"
} > "$DEST"

bash -n "$DEST"
echo "Wrote $DEST ($(grep -c '^alias ' "$DEST") aliases)"
